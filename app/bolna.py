"""Bolna Voice Agent In-Flight Guardrail Middleware & Symphony Supervision Bridge.
Designed for Y Combinator x Symphony Buildathon (Symphony 2026 Voice AI Summit, Bengaluru).

Bolna (open-source voice AI orchestrator) voice agents stream their candidate utterances
through this sub-10ms guardrail middleware before audio synthesis. If an uncompliant claim
or abusive prompt injection occurs, CallGuard immediately halts the TTS audio stream and
injects an approved regulatory replacement while streaming an alert card to Symphony.
"""

import time
import uuid
from typing import Dict, List, Optional
from pydantic import BaseModel, Field

from .engine import CallSession, list_packs
from .nlp import normalize
from .symphony import post_audit


class BolnaGuardrailRequest(BaseModel):
    agent_id: str = Field(default="bln-agent-voice-01", description="Unique identifier for the Bolna voice agent")
    pack: str = Field(default="finance", description="Active policy pack (finance, india_bfsi, healthcare, collections)")
    text: str = Field(..., description="Candidate spoken utterance generated by Bolna agent LLM")
    speaker: str = Field(default="Agent", description="Speaker identity (Agent / Advisor)")
    session_id: Optional[str] = Field(default=None, description="Optional call session ID")
    model: Optional[str] = Field(default="llama-3.3-70b-instruct", description="Underlying LLM used by Bolna agent")


class BolnaGuardrailResponse(BaseModel):
    action: str  # ALLOW | INTERRUPT_AND_REPLACE
    allowed: bool
    latency_ms: float
    original_text: str
    safe_text: str
    halt_tts: bool
    violation: Optional[dict] = None
    agent_id: str
    session_id: str
    policy_pack: str
    symphony_alert_dispatched: bool = False


